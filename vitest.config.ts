/*
==================================================
شرح الملف للمبتدئ
==================================================

اسم الملف:
vitest.config.ts

وظيفة الملف:
إعدادات مكتبة الاختبارات Vitest: أين يجد الاختبارات
(ضمن src في ملفات *.test.ts) وكيف يفهم الاختصار '@'
الذي يشير إلى مجلد src (نفس الاختصار المستخدم في التطبيق).

لماذا نحتاجه؟
بدون alias '@'، لن يعرف Vitest ما معنى استيرادات مثل
'@/lib/utils' التي تملأ ملفات الاختبار، وستفشل كل الاختبارات.

متى يعمل؟
عند تشغيل: npm test

من يستدعيه؟
سكربت npm (test) من package.json.
==================================================
*/

// ========================================
// 1. الاستيرادات
// ========================================
// defineConfig: دالة مساعدة من مكتبة vitest/config (node_modules).
// path: أداة Node.js للتعامل مع المسارات (من اللغة نفسها).
import { defineConfig } from 'vitest/config';
import path from 'path';

// ========================================
// 2. الإعدادات
// ========================================
// export default: نُخرج كائن الإعدادات ليتعرف عليه Vitest.
export default defineConfig({
  test: {
    environment: 'node', // الاختبارات تعمل في بيئة Node (بدون متصفح)
    include: ['src/**/*.test.ts'], // أين نبحث عن ملفات الاختبار
  },
  resolve: {
    alias: {
      // '@' في الاستيرادات = مجلد src (مثل إعداد tsconfig/Next).
      '@': path.resolve(__dirname, 'src'),
    },
  },
});
