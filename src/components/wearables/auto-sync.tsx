// useEffect: تنفيذ كود عند ظهور المكوّن.
import { useEffect } from 'react';

/**
 * مزامنة مستمرة صامتة: عند فتح لوحة التحكم تُطلب مزامنة اتصالات الجهاز
 * المستحقة دون إزعاج المستخدم (نتيجة تظهر في سجلات المزامنة فقط).
 */
export function AutoSync() {
  useEffect(() => {
    // cancelled: هل خرج المستخدم من الصفحة قبل اكتمال الطلب؟
    let cancelled = false;
    // نرسل طلب المزامنة التلقائية.
    fetch('/api/wearables/sync-auto', { method: 'POST' })
      .then((r) => r.json())
      .then((d) => {
        if (cancelled) return;
        // إن فشل بعض الاتصالات نكتب تحذيرًا في console فقط
        // (دون إظهار رسالة للمستخدم).
        if (d?.results?.some((x: { ok: boolean }) => !x.ok)) {
          console.warn('auto-sync partial failure', d.results);
        }
      })
      // أي خطأ في الشبكة يُتجاهل بصمت — هذه مزامنة خلفية.
      .catch(() => undefined);
    // عند الخروج من الصفحة نوقف أي تحديث لاحق.
    return () => {
      cancelled = true;
    };
  }, []);
  // المكوّن لا يرسم أي شيء مرئي.
  return null;
}
