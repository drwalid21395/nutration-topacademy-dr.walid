/**
 * توليد التوصيات الإرشادية لأيام التدريب والراحة والبطولة.
 * جميع النصوص عربية إرشادية غير علاجية.
 */
import type { NutritionResult } from '@/types';

export function buildRecommendations(
  result: NutritionResult,
  opts: {
    goal?: string;
    hasDoubleTraining?: boolean;
    nextCompetitionDate?: Date | null;
    swimMinutesPerSession?: number;
  }
): Record<string, string> {
  const recs: Record<string, string> = {};

  recs['trainingDay'] =
    `في أيام التدريب وجّه جزءًا أكبر من الكربوهيدرات نحو وجبة ما قبل التمرين (قبل 2-3 ساعات) ` +
    `ووجبة ما بعد التمرين (خلال 30-60 دقيقة) لدعم التعافي، مع شرب ${Math.round(
      (opts.swimMinutesPerSession ?? 60) * 12
    )} مل من الماء أثناء الجلسة على دفعات.`;

  recs['restDay'] =
    'في أيام الراحة قلّل الكربوهيدرات قليلًا واحتفظ بالبروتين لنفس المستوى لدعم الاستشفاء العضلي، ' +
    'وحافظ على شرب الماء بمستوى عادي دون إفراط.';

  if (opts.hasDoubleTraining) {
    recs['doubleTraining'] =
      'في أيام التدريب المزدوج (صباحًا ومساءً) تناول وجبة كربوهيدراتية معتدلة بعد التمرين الأول مباشرة، ' +
      'ووجبة خفيفة قبل التمرين الثاني، مع تعويض السوائل بين الجلستين وتأكيد النوم الكافي ليلًا.';
  }

  if (opts.nextCompetitionDate) {
    recs['competitionWeek'] =
      'الأسبوع السابق للبطولة: ثبّت مواعيد الوجبات، لا تجرّب أطعمة أو مكملات جديدة، ' +
      'زد الكربوهيدرات تدريجيًا في الأيام الأخيرة (تحميل كربوهيدرات)، وقلّل حجم الحصة قبل السباق مباشرة.';
    recs['competitionDay'] =
      'يوم البطولة: افطر قبل السباق بـ 3-4 ساعات على وجبة مألوفة منخفضة الدهون والألياف، ' +
      'وشرب السوائل قبل السباق بـ 30-60 دقيقة، وبين السباقات تناول وجبات صغيرة سريعة الهضم.';
    recs['postRace'] =
      'بعد كل سباق: خلال 30 دقيقة تناول بروتين + كربوهيدرات سريعة (مشروب تعافي أو ساندويتش + عصير)، ' +
      'وعوّض السوائل بنسبة 125-150% من ما فقدته، وتجنّب الأطعمة الدسمة حتى نهاية اليوم.';
  }

  if (opts.goal === 'fatLoss') {
    recs['fatLoss'] =
      'هدف خفض الدهون: خلق عجز سعري معتدل مع الحفاظ على البروتين العالي، وعدم خفض السعرات تحت الحد الآمن، ' +
      'ومتابعة الوزن أسبوعيًا. القاصرون وأصحاب الحالات الصحية يحتاجون إشراف اختصاصي.';
  }

  if (opts.goal === 'muscleGain') {
    recs['muscleGain'] =
      'هدف زيادة الكتلة: فائض سعري خفيف مع بروتين كافٍ موزّع على الوجبات، وتدريب مقاومة منتظم، ' +
      'ونوم لا يقل عن 7-9 ساعات.';
  }

  recs['hydration'] =
    `احتياج السوائل الإجمالي التقديري ${Math.round(result.waterMl ?? 0)} مل/يوم، ` +
    'يختلف حسب الحرارة ومدة التمرين، ولون البول مؤشر عملي: أصفر فاتح يعني ترطيبًا جيدًا.';

  recs['micronutrients'] =
    'احتياجات الحديد والكالسيوم وفيتامين D مهمة للسباحين؛ تعامل معها غذائيًا أولًا، ' +
    'ولا تُؤخذ مكملات إلا بعد فحص طبي وتوجيه اختصاصي.';

  recs['supplements'] =
    'لا يوجد مكمل يُعوّض نمط غذاء ضعيفًا. المكملات اختيارية وتحت مراجعة طبية، ' +
    'مع التحقق من خلوها من المواد المحظورة وفق لوائح مكافحة المنشطات.';

  return recs;
}
