/*
==================================================
شرح الملف للمبتدئ
==================================================

اسم الملف:
src/app/api/nutrition/today/route.ts

وظيفة الملف:
واجهة API بحرف GET تعيد "حالة التغذية الديناميكية لليوم":
ما أكله السباح، الهدف المتبقي، الماء، التدريبات... كل ما
تحتاجه لوحة السباح اليومية في طلب واحد.

لماذا نحتاجه؟
لوحة اليوم الرئيسية تعرض كل شيء دفعة واحدة (سعرات مستهلكة
مقابل الهدف، بروتين، ماء، سعرات محروقة...) — هذه الدالة
تجمّع كل ذلك من قاعدة البيانات.

متى يعمل؟
عند وصول طلب GET إلى /api/nutrition/today.

ترتيب التنفيذ (قصة الطلب):
1. من المستخدم؟ لو غير مسجل → 401.
2. نستدعي getTodayState لبناء الحالة الكاملة لليوم.
3. نرجع الحالة كما هي للوحة.

ماذا يعني HTTP Status؟
- 200: نجاح. 401: غير مسجل.

العلاقة مع الملفات:
- getCurrentUser من lib/auth.
- getTodayState من lib/nutrition/dynamic.
==================================================
*/

// ========================================
// 1. الاستيرادات
// ========================================

// NextResponse: أداة Next.js لإرسال الرد. من مكتبة next/server.
import { NextResponse } from 'next/server';
// getCurrentUser: ملف محلي من lib/auth — يتحقق من تسجيل الدخول.
import { getCurrentUser } from '@/lib/auth';
// getTodayState: من lib/nutrition/dynamic — دالة تبني "حالة اليوم"
// الكاملة (الهدف، المستهلك، المتبقي) للمستخدم المعطى.
import { getTodayState } from '@/lib/nutrition/dynamic';

// ========================================
// 2. معالج الطلب GET
// ========================================

// export async function GET:
// اسم الدالة = نوع الطلب. Next.js يستدعي GET تلقائيًا
// عند وصول طلب GET إلى /api/nutrition/today.
/** حالة التغذية الديناميكية لليوم (لوحة السباح). */
export async function GET() {
  // الخطوة 1: تحقق من تسجيل الدخول.
  const user = await getCurrentUser();
  if (!user) return NextResponse.json({ error: 'يجب تسجيل الدخول' }, { status: 401 });

  // الخطوة 2: بناء حالة اليوم كاملة من قاعدة البيانات.
  const state = await getTodayState(user.id);
  // الخطوة 3: نعيد الحالة مباشرة (لا نلفها في حقل إضافي).
  return NextResponse.json(state);
}
