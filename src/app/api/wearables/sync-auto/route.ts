/*
==================================================
شرح الملف للمبتدئ
==================================================

اسم الملف:
src/app/api/wearables/sync-auto/route.ts

وظيفة الملف:
واجهة API بحرف POST تُشغّل «المزامنة التلقائية» للمستخدم
الحالي فقط: عند فتح لوحة الساعات، يطلب المتصفح هذا المسار
بهدوء (في الخلفية) فيزامِن اتصالات هذا المستخدم المستحقة
بدون إزعاج تجربته أو حجب الصفحة.

لماذا نحتاجه؟
حتى يجد السباح بياناته محدثة تلقائيًا كلما فتح التطبيق،
دون أن يضغط «مزامنة» بنفسه، ودون انتظار الجدولة المركزية.

متى يعمل؟
عند استقبال طلب POST إلى /api/wearables/sync-auto
(يُرسله المتصفح بعد تحميل لوحة الساعات، في الخلفية).

من يستدعي هذا الملف؟
صفحة لوحة الساعات الذكية (بعد تحميلها، بصمت).

الملفات التي يتعامل معها:
- getCurrentUser من lib/auth.
- findDueConnections + runSyncConnection من lib/wearables/sync.

ترتيب العمل:
1. غير مسجل → 401.
2. نجلب اتصالات هذا المستخدم المستحقة للمزامنة.
3. لو لا شيء مستحق → نرجع نجاحًا فارغًا برسالة واضحة.
4. نزامِن كل اتصال مستحق ونجمع النتائج.
5. نرجع النتائج.
==================================================
*/

// ========================================
// 1. الاستيرادات
// ========================================

// NextResponse: أداة Next.js لإرسال الرد. من مكتبة next/server.
// (لا نستورد NextRequest لأننا لا نقرأ جسم طلب هنا.)
import { NextResponse } from 'next/server';
// getCurrentUser: دالة محلية من lib/auth تعيد المستخدم الحالي.
import { getCurrentUser } from '@/lib/auth';
// findDueConnections: تعيد الاتصالات المستحقة لمستخدم معيّن.
// runSyncConnection: تشغيل مزامنة كاملة لاتصال واحد.
// كلاهما من lib/wearables/sync (محلي).
import { findDueConnections, runSyncConnection } from '@/lib/wearables/sync';

// ========================================
// 2. معالج المزامنة التلقائية (POST)
// ========================================

/**
 * مزامنة تلقائية عند فتح التطبيق: تُشغَّل من المتصفح بعد تحميل اللوحة
 * للمزامنة المستمرة (غير الحاجبة) لاتصالات الجهاز المستحقة.
 */
// POST: مزامنة خلفية للمستخدم الحالي فقط عند فتح اللوحة.
export async function POST() {
  // الخطوة 1: تحقق من تسجيل الدخول.
  const user = await getCurrentUser();
  if (!user) return NextResponse.json({ error: 'يجب تسجيل الدخول' }, { status: 401 });

  // الخطوة 2: البحث عن الاتصالات المستحقة لهذا المستخدم فقط
  // (التي مر على آخر مزامنة لها أكثر من ١٥ دقيقة).
  const due = await findDueConnections(user.id);
  // الخطوة 3: لو لا شيء مستحق → نجاح فوري ورسالة واضحة.
  if (due.length === 0) return NextResponse.json({ ok: true, results: [], message: 'لا مزامنة مستحقة.' });

  // الخطوة 4: مزامنة كل اتصال مستحق وجمع النتائج.
  const results = [];
  for (const conn of due) {
    const r = await runSyncConnection(conn);
    results.push(r);
  }

  // الخطوة 5: إرجاع نتائج المزامنة.
  return NextResponse.json({ ok: true, results });
}
