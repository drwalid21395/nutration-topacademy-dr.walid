/*
==================================================
شرح الملف للمبتدئ
==================================================

اسم الملف:
src/app/api/push/public-key/route.ts

وظيفة الملف:
واجهة API بحرف GET بسيطة تعيد "المفتاح العام" الخاص
بإشعارات الدفع (VAPID) حتى يستطيع المتصفح تفعيل الاشتراك.

لماذا نحتاجه؟
قبل أن يتلقى المتصفح إشعارات دفع، يحتاج إلى المفتاح العام
المطابق للمفتاح السري المخزن في الخادم، ليعمل التشفير
بين المتصفح والخادم.

متى يعمل؟
عند وصول طلب GET إلى /api/push/public-key.

ترتيب التنفيذ (قصة الطلب):
1. من المستخدم؟ لو غير مسجل → 401.
2. نجلب المفتاح العام من إعدادات البيئة (getVapidPublicKey).
3. لو المفتاح غير مفعل/غير موجود → 503.

ماذا يعني HTTP Status؟
- 200: نجاح. 401: غير مسجل.
- 503: الدفع غير مفعل (الخدمة غير متاحة).

العلاقة مع الملفات:
- getCurrentUser من lib/auth.
- getVapidPublicKey من lib/push.
==================================================
*/

// ========================================
// 1. الاستيرادات
// ========================================

// NextResponse: أداة Next.js لإرسال الرد. من مكتبة next/server.
import { NextResponse } from 'next/server';
// getCurrentUser: ملف محلي من lib/auth — يتحقق من تسجيل الدخول.
import { getCurrentUser } from '@/lib/auth';
// getVapidPublicKey: من lib/push — تجلب المفتاح العام لإشعارات
// الدفع (VAPID) من إعدادات البيئة.
import { getVapidPublicKey } from '@/lib/push';

// ========================================
// 2. معالج الطلب GET
// ========================================

// export async function GET:
// Next.js يستدعي GET تلقائيًا عند وصول طلب GET لهذا المسار.
/** إرجاع مفتاح VAPID العام لتفعيل اشتراك الدفع في المتصفح. */
export async function GET() {
  // الخطوة 1: تحقق من تسجيل الدخول.
  const me = await getCurrentUser();
  if (!me) return NextResponse.json({ error: 'يجب تسجيل الدخول' }, { status: 401 });

  // الخطوة 2: جلب المفتاح العام من إعدادات البيئة.
  const key = await getVapidPublicKey();
  // لو المفتاح غير مضبوط في البيئة → نعطي 503 (الخدمة غير متاحة).
  if (!key) return NextResponse.json({ error: 'الدفع غير مفعل' }, { status: 503 });

  return NextResponse.json({ publicKey: key });
}
