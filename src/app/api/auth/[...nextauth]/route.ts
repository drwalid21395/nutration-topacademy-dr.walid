/*
==================================================
شرح الملف للمبتدئ
==================================================

اسم الملف:
src/app/api/auth/[...nextauth]/route.ts

وظيفة الملف:
نقطة الالتقاء الرسمية لمكتبة NextAuth (مكتبة تسجيل الدخول).
ملف صغير (6 أسطر) يعيد توجيه كل طلبات الدخول والخروج
والتوكن إلى المعالج الجاهز من NextAuth.

لماذا نحتاجه؟
أي عملية تسجيل دخول/خروج/تجديد جلسة تمر من هذا المسار،
فبدونه لا تعمل صفحات الدخول ولا حماية المسارات.

متى يعمل؟
عند وصول أي طلب (GET أو POST) إلى أي مسار يبدأ بـ
/api/auth/[...nextauth] مثل:
- POST /api/auth/callback/credentials (تسجيل الدخول بالبريد وكلمة المرور)
- GET /api/auth/session (جلب حالة الجلسة)
- POST /api/auth/signout (تسجيل الخروج)

من يستدعي هذا الملف؟
كل مكونات src/app وsrc/components التي تستخدم
signIn / signOut / useSession من مكتبة next-auth/react.

الملفات التي يتعامل معها:
- authOptions من lib/auth: ملف يحوي إعدادات المصادقة كاملة
  (مزوّد البريد/كلمة المرور، خيارات قاعدة البيانات، دوال التصديق).
==================================================
*/

// ========================================
// 1. الاستيرادات
// ========================================

// NextAuth: المكتبة الخارجية نفسها — تصنع معالجًا جاهزًا
// لكل طلبات المصادقة (دخول/خروج/جلسة/توكن).
import NextAuth from 'next-auth';
// authOptions: ملف محلي من lib/auth — كل إعدادات المصادقة
// (كيف يتحقق من البريد وكلمة المرور، وأي حقول يعيدها).
import { authOptions } from '@/lib/auth';

// ========================================
// 2. إنشاء المعالج
// ========================================

// نُنشئ المعالج مرة واحدة بالإعدادات المحفوظة في authOptions.
// NextAuth يعتني بباقي التفاصيل داخليًا (جلسات، توكن، تشفير...).
const handler = NextAuth(authOptions);

// Next.js يتوقع دالة لكل طريقة طلب.
// نُصدّر نفس المعالج باسم GET وPOST ليستقبل كل الطلبات،
// إذ قد يحمل المتصفح/التطبيق طلبات بالطريقتين.
export { handler as GET, handler as POST };
