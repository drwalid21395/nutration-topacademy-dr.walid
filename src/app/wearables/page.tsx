// ========================================
// 1. الاستيرادات
// ========================================

import { redirect } from 'next/navigation'; // redirect: نقل لصفحة أخرى — من مكتبة next/navigation.
import { getCurrentUser } from '@/lib/auth'; // دالة محلية: المستخدم المسجل حاليًا.
import { WearablesPage } from '@/components/wearables/wearables-page'; // مكوّن صفحة الربط — ملف محلي.

// ========================================
// 2. بيانات التعريف
// ========================================

// metadata: عنوان الصفحة في تبويب المتصفح.
export const metadata = { title: 'ربط الساعة الذكية' };

// ========================================
// 3. الصفحة الرئيسية (تعمل في الخادم)
// ========================================

// WearablesRoute: الدالة الرئيسية للصفحة (تعمل في الخادم).
// اسم الدالة مختلف قليلًا عن البقية لكن دوره هو نفسه.
export default async function WearablesRoute() {
  // الخطوة 1: من هو المستخدم؟ لو زائر → صفحة الدخول.
  const user = await getCurrentUser();
  if (!user) redirect('/login');

  // الخطوة 2: عرض مكوّن الربط — user يحدد لمن يُربط الجهاز.
  return <WearablesPage user={user} />;
}
