/** أدوات أمان عامة: تحديد معدل الطلبات، التعقيم، تسجيل العمليات الحساسة */

// ========================================
// 1. تحديد معدل الطلبات
// ========================================

// RATE_LIMITS: خريطة (Map) تخزن لكل مفتاح عدد الطلبات
// وموعد انتهاء النافذة الزمنية.
// Map = بنية بيانات تخزن "مفتاح → قيمة" مثل قاموس.
const RATE_LIMITS = new Map<string, { count: number; resetAt: number }>();

/*
-----------------------------------------
الدالة: rateLimit
-----------------------------------------
وظيفتها: هل يسمح بهذا الطلب أم لا؟
Input:
- key: مفتاح (مثل `calc:user123` أو `register:IP`).
- limit: أقصى عدد مسموح خلال النافذة.
- windowMs: طول النافذة بالمللي ثانية (60_000 = دقيقة).
Output: true = مسموح، false = تجاوز الحد.

ترتيب التنفيذ:
1. نأخذ وقت الآن.
2. نبحث عن السجل السابق لهذا المفتاح.
3. لو لا يوجد أو انتهت النافذة → نسجل أول طلب ونسمح.
4. لو وصل الحد → نمنع.
5. وإلا نزيد العدد ونسمح.

ملاحظة تعليمية:
هذا الحل "في الذاكرة" (Memory) — مناسب لخادم واحد.
في الإنتاج الموزع يُفضّل Redis/Upstash.
يتم استدعاؤها من: واجهات API (register, calculator, ...)
-----------------------------------------
*/
export function rateLimit(key: string, limit = 10, windowMs = 60_000): boolean {
  const now = Date.now(); // الوقت الآن بالمللي ثانية
  const entry = RATE_LIMITS.get(key); // السجل السابق
  // لو لا يوجد سجل، أو انتهت مدة النافذة → ابدأ عدًا جديدًا.
  if (!entry || entry.resetAt < now) {
    RATE_LIMITS.set(key, { count: 1, resetAt: now + windowMs });
    return true;
  }
  // لو العدد وصل الحد → ارفض الطلب.
  if (entry.count >= limit) return false;
  // وإلا زد العد واسمح.
  entry.count += 1;
  return true;
}

// ========================================
// 2. تعقيم النصوص
// ========================================

/*
-----------------------------------------
الدالة: sanitizeText
-----------------------------------------
وظيفتها: تحويل أحرف HTML الخطيرة إلى رموز آمنة لا تُنفَّذ.
مثال: <script> تتحول إلى &lt;script&gt; فيظهر كنص فقط ولا يعمل.
Input: نص. Output: نص منقّى (أقصى 5000 حرف).
يتم استدعاؤها من: register/route.ts (تنظيف الاسم والهاتف).
-----------------------------------------
*/
/** تعقيم نص من HTML الخبيث */
export function sanitizeText(input: string | null | undefined): string {
  if (!input) return '';
  return input
    .replace(/</g, '&lt;') // < → &lt;
    .replace(/>/g, '&gt;') // > → &gt;
    .replace(/"/g, '&quot;') // " → &quot;
    .replace(/'/g, '&#39;') // ' → &#39;
    .slice(0, 5000); // نقتطع الطول حتى لا تُرسل نصوص ضخمة
}

