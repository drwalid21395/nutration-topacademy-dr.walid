import { prisma } from '@/lib/prisma';

/*
-----------------------------------------
الدالة: audit
-----------------------------------------
وظيفتها: تسجيل عملية مهمة في جدول AuditLog.
Input: userId, action (مثل 'auth.register'), entity, entityId, metadata.
Output: بلا (لا نكسر سير العمل لو فشل التسجيل).
يتم استدعاؤها من: register وcalculator وكل الواجهات الحساسة.
-----------------------------------------
*/
/** تسجيل عملية في سجل التدقيق (لا تسجل بيانات حساسة) */
export async function audit(
  userId: string | null,
  action: string,
  entity?: string,
  entityId?: string,
  metadata?: Record<string, unknown>
) {
  try {
    // prisma.auditLog.create: نضيف صفًا جديدًا في جدول AuditLog.
    await prisma.auditLog.create({
      data: {
        userId,
        action,
        entity,
        entityId,
        // JSON.stringify: نحول الكائن إلى نص ليُخزَّن في عمود نصي.
        metadata: JSON.stringify(metadata ?? {}),
      },
    });
  } catch {
    // التعليق الأصلي: لا نريد كسر سير العمل عند فشل التسجيل.
    // أي لو فشل تسجيل العملية نكمل البرنامج بشكل طبيعي.
  }
}

// ========================================
// 4. فحص الكود المشبوه
// ========================================

/** هل النص يحتوي HTML/JS مشبوه؟ */
export function containsMarkup(input: string): boolean {
  // Regular Expression (RegExp): نمط بحث نصي.
  // يبحث عن: < ثم حرف، أو javascript:، أو onclick=، أو <script>...
  return /<[a-zA-Z/!]|javascript:|on\w+\s*=|<\s*(script|iframe|object|embed)/i.test(input);
}
