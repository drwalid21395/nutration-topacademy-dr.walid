// ========================================
// 1. استيراد العميل
// ========================================

// PrismaClient: يأتي من مكتبة @prisma/client (مولّدة تلقائيًا
// من schema.prisma بأمر prisma generate).
// ليست من JavaScript نفسها — مكتبة خارجية مثبتة في المشروع.
import { PrismaClient } from '@prisma/client';

// ========================================
// 2. الاتصال المشترك
// ========================================

// globalThis: الكائن العام (موجود دائمًا في Node.js).
// نضيف له خاصية prisma اختيارية لتخزين الاتصال.
const globalForPrisma = globalThis as unknown as { prisma?: PrismaClient };

// ننشئ الاتصال: إما نأخذ المتخزن سابقًا (globalForPrisma.prisma)
// أو ننشئ اتصالًا جديدًا.
export const prisma =
  globalForPrisma.prisma ??
  new PrismaClient({
    // log: يحدد مستوى السجلات.
    // في التطوير: نرى التحذيرات والأخطاء فقط (قلّة ضوضاء).
    // في الإنتاج: الأخطاء فقط.
    log: process.env.NODE_ENV === 'development' ? ['warn', 'error'] : ['error'],
  });

// لو نحن في بيئة غير الإنتاج → نخزّن الاتصال في الكائن العام
// حتى يُعاد استخدامه عند إعادة تحميل الملفات في التطوير.
if (process.env.NODE_ENV !== 'production') {
  globalForPrisma.prisma = prisma;
}
